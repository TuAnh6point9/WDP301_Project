import { Router } from 'express';
import { stationSchema, stationUpdateSchema } from '@wqi/contracts';
import * as controller from './station.controller.js';
import { adminOnly } from '../../middleware/authenticate.js';
import { validate } from '../../middleware/validate.js';
import { audited } from '../audit/audit.service.js';
export const stationRouter = Router();
stationRouter.get('/', controller.list);
stationRouter.get('/:id', controller.get);
stationRouter.post('/', adminOnly, audited('station.create'), validate(stationSchema), controller.create);
stationRouter.patch('/:id', adminOnly, audited('station.update'), validate(stationUpdateSchema), controller.update);
stationRouter.delete('/:id', adminOnly, audited('station.deactivate'), controller.deactivate);
