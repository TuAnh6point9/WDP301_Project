import { existsSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { MongoMemoryServer } from 'mongodb-memory-server';
import mongoose from 'mongoose';
const installedBinary = 'C:/Program Files/MongoDB/Server/8.3/bin/mongod.exe';
const systemBinary = process.env.MONGOMS_SYSTEM_BINARY || (existsSync(installedBinary) ? installedBinary : undefined);
const mongo = await MongoMemoryServer.create({ binary: { systemBinary }, instance: { ip: '127.0.0.1', dbName: 'akh_wqi_e2e' } });
process.env.NODE_ENV = 'test';
process.env.PORT = '5001';
process.env.MONGODB_URI = mongo.getUri();
process.env.CLIENT_ORIGIN = 'http://127.0.0.1:5174';
process.env.SESSION_SECRET = randomBytes(32).toString('hex');
process.env.AI_MODE = 'disabled';
const { createApp } = await import('../server/src/app.js');
const { connectDatabase } = await import('../server/src/config/database.js');
const { User } = await import('../server/src/modules/users/user.model.js');
const { Station } = await import('../server/src/modules/stations/station.model.js');
const { WaterRecord } = await import('../server/src/modules/water-records/water-record.model.js');
const { ImportBatch, ImportedRow } = await import('../server/src/modules/imports/import.model.js');
const { Prediction } = await import('../server/src/modules/predictions/prediction.model.js');
const { hashPassword } = await import('../server/src/modules/auth/auth.service.js');
await connectDatabase();
for (const model of [User, Station, WaterRecord, ImportBatch, ImportedRow, Prediction]) await model.createIndexes();
await User.create({ name: 'Test administrator', email: 'admin@example.test', passwordHash: await hashPassword('isolated-test-password'), role: 'admin' });
await User.create({ name: 'Test user', email: 'user@example.test', passwordHash: await hashPassword('isolated-test-password'), role: 'user' });
const app = createApp();
const server = app.listen(5001, '127.0.0.1', () => console.log('Isolated E2E server ready'));
let stopping = false;
async function stop() {
  if (stopping) return;
  stopping = true;
  server.close();
  await app.locals.sessionStore.close();
  await mongoose.disconnect();
  await mongo.stop();
  process.exit(0);
}
process.once('SIGTERM', () => { void stop(); });
process.once('SIGINT', () => { void stop(); });
